CREATE TABLE IF NOT EXISTS public.admin_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type text NOT NULL,
  title text NOT NULL,
  details text NOT NULL,
  reference_code text,
  customer_name text,
  booking_id text,
  actor_name text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS admin_logs_created_at_idx
  ON public.admin_logs (created_at DESC);

ALTER TABLE public.admin_logs ENABLE ROW LEVEL SECURITY;

GRANT SELECT, INSERT ON public.admin_logs TO anon, authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.admin_logs_id_seq TO anon, authenticated;

DROP POLICY IF EXISTS "Allow dashboard admins to read activity logs" ON public.admin_logs;
DROP POLICY IF EXISTS "Allow dashboard admins to insert activity logs" ON public.admin_logs;

CREATE POLICY "Allow dashboard admins to read activity logs"
  ON public.admin_logs FOR SELECT TO anon, authenticated USING (true);

CREATE POLICY "Allow dashboard admins to insert activity logs"
  ON public.admin_logs FOR INSERT TO anon, authenticated WITH CHECK (true);

NOTIFY pgrst, 'reload schema';
