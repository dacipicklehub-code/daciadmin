CREATE TABLE IF NOT EXISTS public.blocked_time_slots (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  blocked_date date NOT NULL,
  time_slot text NOT NULL,
  court text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (blocked_date, time_slot, court)
);

WITH ranked_slots AS (
  SELECT
    id,
    row_number() OVER (
      PARTITION BY
        blocked_date,
        time_slot,
        CASE
          WHEN lower(trim(court)) IN ('training area', 'training court', 'court two', 'court2', 'court 2', '2') THEN 'Court 2'
          ELSE court
        END
      ORDER BY id
    ) AS duplicate_rank
  FROM public.blocked_time_slots
)
DELETE FROM public.blocked_time_slots AS slots
USING ranked_slots
WHERE slots.id = ranked_slots.id
  AND ranked_slots.duplicate_rank > 1;

UPDATE public.bookings
SET court = 'Court 2'
WHERE lower(trim(court)) IN ('training area', 'training court', 'court two', 'court2', 'court 2', '2');

UPDATE public.bookings
SET court_name = 'Court 2'
WHERE lower(trim(court_name)) IN ('training area', 'training court', 'court two', 'court2', 'court 2', '2')
  AND court_name <> 'Court 2';

UPDATE public.blocked_time_slots
SET court = 'Court 2'
WHERE lower(trim(court)) IN ('training area', 'training court', 'court two', 'court2', 'court 2', '2')
  AND court <> 'Court 2';

ALTER TABLE public.blocked_time_slots ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, DELETE ON public.blocked_time_slots TO anon, authenticated;

DROP POLICY IF EXISTS "Allow public read blocked time slots" ON public.blocked_time_slots;
DROP POLICY IF EXISTS "Allow dashboard admins to insert blocked time slots" ON public.blocked_time_slots;
DROP POLICY IF EXISTS "Allow dashboard admins to delete blocked time slots" ON public.blocked_time_slots;

CREATE POLICY "Allow public read blocked time slots"
  ON public.blocked_time_slots FOR SELECT TO anon, authenticated USING (true);

CREATE POLICY "Allow dashboard admins to insert blocked time slots"
  ON public.blocked_time_slots FOR INSERT TO anon, authenticated WITH CHECK (true);

CREATE POLICY "Allow dashboard admins to delete blocked time slots"
  ON public.blocked_time_slots FOR DELETE TO anon, authenticated USING (true);

